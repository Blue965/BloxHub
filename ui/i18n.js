function bloxhubT(key, vars) {
  const lang = window.BloxHubLang || "fr";
  let s = (I18N[lang] && I18N[lang][key]) || I18N.fr[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split("{" + k + "}").join(String(v));
    }
  }
  return s;
}

function bloxhubApplyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = bloxhubT(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = bloxhubT(el.getAttribute("data-i18n-ph"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = bloxhubT(el.getAttribute("data-i18n-title"));
  });
  document.documentElement.lang = window.BloxHubLang || "fr";
}

window.BloxHubI18N = I18N;
window.BloxHubT = bloxhubT;
window.BloxHubApplyI18n = bloxhubApplyI18n;
